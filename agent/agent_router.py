# --- 4. THE AI AGENT ROUTER ---
def route_user_request(user_message, api_key):
    """Uses Groq to decide which tool to use based on the user's message."""

    client = Groq(api_key=api_key)

    system_prompt = """
    You are an AI router for the AquaGuard agriculture app.
    Read the user's message and reply with ONLY ONE exact word from this list:
    - CALCULATE (if the user wants to calculate water needs, crop demand, or irrigation volume)
    - COMPARE (if the user wants to compare two irrigation scenarios)
    - SEARCH (if the user is asking a general knowledge question about farming, crops, or groundwater)

    Do not add any other words, greetings, or punctuation.
    """

    response = client.chat.completions.create(
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_message}
        ],
        model="openai/gpt-oss-20b",
        temperature=0.0
    )

    decision = response.choices[0].message.content.strip().upper()
    print(f"Agent Routing Decision: {decision}")

    # --- EXECUTION GATEWAY ---
    if "CALCULATE" in decision:
        return run_water_calculations(user_message)
    elif "COMPARE" in decision:
        return compare_scenarios(5000, 3500)
    elif "SEARCH" in decision:
        return answer_question_with_rag(user_message)
    else:
        return "System Guardrail: Request not recognized."
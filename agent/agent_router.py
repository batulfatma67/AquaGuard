def compare_scenarios(baseline_volume, alternative_volume):
    """Calculates the potential scenario difference in groundwater volume."""
    saved_water = baseline_volume - alternative_volume

    if saved_water > 0:
        return f"Scenario Tool Triggered: By switching to the alternative scenario, you save {saved_water} cubic meters of groundwater."
